import { normalizeName } from "@/lib/text";

/**
 * 名字**形态**判定：这个名字是「专名」还是「称谓」。
 *
 * ## 为什么需要它
 *
 * `merge.ts` 的 `pickCanonicalKey` 原本只按**出现频次**选规范名
 * （同频次才取较短者）。而书里对人物的**称谓**出现次数**必然多于**本名：
 * 《儒林外史》里「马二先生」全书出现几十次，本名「马纯上」只出现几次
 * ⇒ 规范名落成 **「马二先生」**，用户看到的实体名是敬称而非本名。
 *
 * 实测（儒林外史重跑后 428 个人物）：**18 个**实体的规范名是称谓、
 * 而本名**已经在它的别名里**（`马二先生→马纯上`、`卫先生→卫体善`、
 * `李老爷→李梦阳`、`倪老爹→倪霜峰` …）。这类问题**不需要新知识**，
 * 只要在选择规范名时**优先选专名**即可修复。
 *
 * ## 为什么不复用 `entity-gate.ts` 的词表
 *
 * 闸门的 `appellationWords` / `officeSuffixes` / `occupationSuffixes`
 * **被 P1 输出侧消费**（注入提示词的候选词典与闸门共用同一批表）。
 * 往那些表里加词会**改变提示词** ⇒ 改变 P1 的 LLM 输出 ⇒
 * **无法在现有图谱上 $0 预演**（见 `entity-gate.ts` 第 3 步的长注释）。
 *
 * 本模块的词表**只被 `pickCanonicalKey` 消费**，是纯 P1 输出侧的后处理，
 * 因此可以在现有图谱上**精确重放**（符合铁律①的「确定性预演」适用范围）。
 *
 * ## 判定口径（保守：宁可少改，不可改错）
 *
 * 只收录**明确的**称谓/敬称/官职/身份/庙号后缀。刻意**不收**单字「公」
 * ——「陈正公」「陈眉公」里的「公」是**字/号**（本名形式），不是敬称；
 * 收了会把正确的规范名误判成称谓。同理不收单字「老」。
 *
 * ⚠️ 与 `pickCanonicalKey` 的配合方式是「**分层**」而不是「**替换**」：
 * 只有当候选键里**确实存在**非称谓形式时，才在专名层内选择；
 * 若全部候选都是称谓形式，则**回退**到原逻辑（频次优先）——
 * 因此本表**漏收**的后果只是「少修一个」，不会「改错一个」。
 */

/**
 * 称谓/敬称/官职/身份/庙号后缀表。
 *
 * 按长度**降序**排列：保证「老先生」先于「先生」被匹配到
 * （对布尔判定而言结果相同，但让最长匹配语义显式）。
 */
export const HONORIFIC_SUFFIXES: readonly string[] = [
  // 尊称 —— 对某人的敬称，不构成本名
  "老先生", "老相公", "老大人", "老夫子",
  "先生", "老爷", "太爷", "老爹", "大爷", "相公", "大人", "老师", "老官",
  // 亲属/女性称谓 —— 原文常以此代称而不给本名
  "夫人", "太太", "奶奶", "姑娘", "小姐", "娘子", "大娘", "二娘", "婆婆",
  // 排行 + 身份 —— 「三公子」「胡八公子」
  "公子", "少爷", "老兄", "世兄",
  // 功名/身份 —— 「严贡生」「张乡绅」
  "乡绅", "贡生", "监生", "举人", "进士", "秀才", "生员",
  // 职业 —— 「杨裁缝」「胡屠户」
  "书办", "管家", "屠户", "裁缝", "盐商", "客人", "媒婆", "卖婆",
  // 官名 —— 「向知县」「蘧太守」
  "太守", "少保", "太保", "中堂", "通政", "知县", "知府", "御史", "侍郎",
  "翰林", "编修", "守备", "总兵", "都督", "巡抚", "布政使", "按察使",
  // 帝王庙号/称谓 —— 「太祖」「成祖」
  "太祖", "成祖", "太宗", "高祖", "皇帝", "天子",
  // 老年男子尊称 —— 「匡太公」「祁太公」
  "太公"
].sort((left, right) => right.length - left.length);

/**
 * **整体型**称谓：词本身就构成一个称谓（不需要前缀）。
 *
 * 与 `HONORIFIC_SUFFIXES` 的区别在于**匹配方式**：
 * - 后缀表要求「前缀 + 后缀」且**严格长于**后缀（`马二先生`），
 *   目的是排除光杆词（「先生」本身是无指代对象的泛称，闸门已拒）；
 * - 本表是**精确相等**（`太祖` / `少保` / `皇帝`），因为「太祖」这类
 *   庙号本身就是对特定帝王的称谓，没有更长的形式。
 *
 * ⚠️ 若把它们混进后缀表并允许等长匹配，会让「先生」这类光杆泛称也被
 * 判成称谓形式 —— 那是另一类问题（无指代对象），不该在本函数里处理。
 */
const WHOLE_HONORIFICS: ReadonlySet<string> = new Set([
  "太祖", "成祖", "太宗", "高祖", "皇帝", "天子",
  "少保", "太保", "中堂", "通政"
]);

/**
 * 本名的常见长度区间（汉字数）。
 *
 * 古典白话小说里的人名以 **2–3 字**为主（`马纯上`/`徐咏`/`平治`），
 * 4 字是上限（`欧阳修` 这类复姓）。超过 4 字的多是描述性短语
 * （`娄太爷的儿子`、`少老爷弟兄两位`）。
 */
const PROPER_NAME_MIN_LENGTH = 2;
const PROPER_NAME_MAX_LENGTH = 4;

/**
 * 不像本名的**尾字**：称谓 / 身份 / 排行 / 泛称的后缀字。
 *
 * ⚠️ 只收**明确**的（哥/兄/弟/女/王/官/翁…），刻意**不收**「阳」「明」「文」
 * 这类**真名常用尾字**（`王阳明`/`董明`），否则会误伤本名。
 */
const NON_NAME_TAIL_CHARS: ReadonlySet<string> = new Set([
  "哥", "兄", "弟", "姐", "妹", "侄", "女", "儿", "娘", "婆", "氏", "爷",
  "公", "翁", "老", "王", "帝", "侯", "相", "官", "房", "司", "厅", "家",
  "亲", "父", "母", "妻", "夫", "孙", "祖", "太", "大", "务", "御",
  // 批 65 预演补收：这些尾字在实测里全部落在非本名一侧
  "伯", "使", "尊", "人", "头", "府", "察", "舍", "郎", "尉", "监",
  "判", "丞", "簿", "史", "吏", "客", "户", "匠", "徒", "役", "爹"
]);

/**
 * 明确的**非名字**（职业/泛称），精确匹配。
 *
 * 这些词**不是称谓**（所以不在 `HONORIFIC_SUFFIXES`），但**也不是本名** ——
 * 若不排除，$0 预演里 `徐先生 → 阴阳` 这类改法会把规范名改得更差。
 */
const NON_NAME_WORDS: ReadonlySet<string> = new Set([
  "阴阳", "才女", "美人", "和尚", "道士", "道人", "尼姑", "僧人",
  "屠户", "裁缝", "管家", "书办", "客人", "娘子", "婆子"
]);

/** 排行/泛称的**首字**（须与后接数字配合才排除，避免误伤「老舍」类）。 */
const NON_NAME_HEAD_CHARS: ReadonlySet<string> = new Set(["老", "小", "大", "阿"]);
const DIGIT_CHARS = /^[一二三四五六七八九十百]$/u;

/**
 * 判断一个名字是否**像本名**（专名形式）。
 *
 * ## 为什么需要「正向判定」而不是「非称谓即本名」
 *
 * 只做「排除称谓」是不够的 —— 排除之后剩下的可能是
 * `才女` / `老二` / `小侄` / `吴王` / `大家兄` 这类**既不是称谓也不是本名**的
 * 写法。$0 预演直接暴露了这一点：若只按「非称谓」筛选，
 * `鲁小姐 → 才女`、`严监生 → 老二`、`太祖 → 吴王` 都会被选出来，
 * 把原本尚可接受的规范名**改得更差**。
 *
 * 因此本函数做**正向**判定：长度落在本名区间、不是称谓形式、
 * 首尾字不是明确的非名字。判不准的一律返回 `false`（保守）——
 * 配合 `pickCanonicalKey` 的「无候选则回退」语义，漏判只会少修，不会改错。
 *
 * @param name 待判名字
 * @returns 像本名时为 true
 */
export function isProperNameForm(name: string): boolean {
  const normalized = normalizeName(name);
  if (
    normalized.length < PROPER_NAME_MIN_LENGTH ||
    normalized.length > PROPER_NAME_MAX_LENGTH
  ) {
    return false;
  }
  if (isHonorificForm(normalized)) {
    return false;
  }
  if (NON_NAME_WORDS.has(normalized)) {
    return false;
  }
  // 尾字是数字 ⇒ 排行称谓（`凤老四`/`姚老五`/`胡老八`），不是本名。
  if (DIGIT_CHARS.test(normalized.slice(-1))) {
    return false;
  }
  if (NON_NAME_TAIL_CHARS.has(normalized.slice(-1))) {
    return false;
  }
  const head = normalized.slice(0, 1);
  const second = normalized.slice(1, 2);
  if (NON_NAME_HEAD_CHARS.has(head) && DIGIT_CHARS.test(second)) {
    return false;
  }
  return true;
}

/**
 * 判断一个名字是否是「称谓形式」（敬称 / 官职 / 身份 / 庙号）。
 *
 * ⚠️ **光杆称谓不算**：`normalized.length` 必须**严格大于**后缀长度。
 * 「先生」本身不是一个「某人的称谓形式」，而是一个无指代对象的泛称
 * （闸门已拒之）；只有「马二先生」这种「前缀 + 称谓」才构成本函数要识别
 * 的形态。
 *
 * @param name 待判名字（原文写法，内部会归一化）
 * @returns 是称谓形式时为 true
 */
export function isHonorificForm(name: string): boolean {
  const normalized = normalizeName(name);
  if (normalized.length === 0) {
    return false;
  }
  // 整体型：词本身即称谓（「太祖」「少保」）。
  if (WHOLE_HONORIFICS.has(normalized)) {
    return true;
  }
  // 组合型：前缀 + 称谓（「马二先生」）。必须**严格长于**后缀，
  // 否则「先生」这类光杆泛称也会被判成「某人的称谓形式」。
  for (const suffix of HONORIFIC_SUFFIXES) {
    if (normalized.length > suffix.length && normalized.endsWith(suffix)) {
      return true;
    }
  }
  return false;
}
