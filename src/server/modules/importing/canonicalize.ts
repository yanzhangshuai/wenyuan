/**
 * 语料规范化：**只做无歧义、可逆的事**（纯函数，零 LLM 成本）。
 *
 * ## 这个模块只解决两类问题
 *
 * 1. **编码层**（{@link normalizeEncoding}）—— BOM / CRLF / 零宽字符。
 *    这是纯粹的编码问题，**没有语义**，归一化不丢任何信息。
 * 2. **结构性噪声行**（{@link stripStructuralNoise}）—— 抓取残留的字数标记、
 *    分隔线、「本章完」标记。它们**整行可枚举**，删掉不丢正文。
 *
 * ## 刻意**不做**的事（每一条都有实测反例）
 *
 * | 不做 | 原因 |
 * | --- | --- |
 * | 页眉页脚 / URL / 推广行 | 两本语料实测命中 **0**；且「像不像页眉」本身要判断 |
 * | 按关键词删行（`整理`/`免费`/`转自`） | 实测在儒林外史误伤 6 段、红楼梦误伤 13 段，**抽样全是正文**（「须臾，整理停当…」） |
 * | 合并「说话人与引语分成两行」 | 那是**另一种合法排版**，携带「谁说了什么」的信号 |
 * | 判定硬折行 | 需要看行长分布（`splitParagraphs` 的第二条判据），清洗判不了 |
 * | 修 OCR 讹字 | 没有「正确形式」的确定性来源 |
 *
 * ## 与「统一规范化」的关系
 *
 * 用户曾提议「导入前把书统一成规范格式，这样解析就不需要差异化处理了」。
 * 这个模块**不是**那个东西：它只把**不需要判断的**部分拿走，
 * 需要判断的部分（硬折行、引语边界、专名）**留在原处**。
 * 理由见 `docs/问题清单与后续工作.md` §3.3 / §3.9。
 *
 * ⚠️ **本模块的两步都已接入导入路径**（`scripts/import-book.ts`）：
 * `normalizeEncoding` 自批次 6 起接线；`stripStructuralNoise` 自批次 9 起接线。
 *
 * 两步的**顺序不可交换**：先归编码（CRLF 归一后 `trim()` 才可靠），再删整行。
 * 接线被推迟到批次 9 的原因：删行会**移动段落序号**，必须与
 * 「提及限制在观测章节内」（N1）攒在一起重导 + 重跑 analyze，一次付费解决两件事。
 * 单独接线的收益不值那次付费。见文档 §3.9 与 §6。
 *
 * ⚠️ 接线的**已知后果**（必须随改动一起记档）：删除行会让段落序号平移。
 * 实测《儒林外史》每回头部都有 `本章字数:N` → 每回叙事段号 **−1**；
 * 《红楼梦》的 `(本章完)` 在**尾部** → 平移 **0**。
 * 因此儒林外史两份金标里的段号需要同步 −1。
 */

/**
 * 零宽 / 不可见格式字符。
 *
 * ⚠️ **刻意不含 `\u2028` / `\u2029`**（行分隔符 / 段分隔符）：
 * 它们**不是零宽字符，是换行符**。当零宽删掉会把两行粘成一行，
 * 而 `splitParagraphs` 的 `[\s\u3000]+` 本来就会把它们折叠成空格。
 * 两本语料实测均为 0 个，所以这条区分目前不影响结果 —— 但改错了方向会。
 */
const ZERO_WIDTH_CHARS = /[\u200b-\u200f\u2060\ufeff]/gu;

/**
 * 编码归一：BOM 剥离、`\r\n`/`\r` → `\n`、零宽字符剥离。
 *
 * ## 为什么必须是一个**独立于 `parseChapters`** 的函数
 *
 * 此前 CRLF 归一化只写在 `parseChapters` **内部**，别处一律拿不到 ——
 * 而红楼梦是 **CRLF（3366 行）**，任何直接读原文的代码（探针、将来的作品包生成器）
 * 都会拿到带 `\r` 的文本。把它提出来，归一化才是**可复用的一步**，
 * 而不是某个函数里的隐式副作用。
 *
 * ## 幂等
 *
 * 对已归一的文本再调用一次结果不变，因此可以在边界与解析器内部各调一次，
 * 不必担心顺序（实测：`parseChapters(normalizeEncoding(x))` 与 `parseChapters(x)`
 * 对两本语料**逐字节相同**）。
 *
 * @param raw 原始文本（UTF-8 解码后的内容）
 * @returns 归一化后的文本
 */
export function normalizeEncoding(raw: string): string {
  return raw.replace(/\r\n?/g, "\n").replace(ZERO_WIDTH_CHARS, "");
}

/** 被删除的一整行。 */
export interface DeletedLine {
  /** **原文**行号（从 1 起，清洗前）。用于把删除结果对回原文。 */
  lineNo: number;
  /** 命中的白名单标签。 */
  label : string;
  /** 被删除的整行内容（已 trim）。 */
  text  : string;
}

/** 结构性噪声剥离的结果。 */
export interface StripNoiseResult {
  /** 剥离后的文本。 */
  text     : string;
  /** **删除区间清单** —— 原文永久保留，删除必须可审计、可回滚。 */
  deletions: DeletedLine[];
}

/** 结构性噪声的行模式：`[标签, 模式]`。 */
type NoisePattern = readonly [label: string, pattern: RegExp];

/**
 * 结构性噪声的**整行**白名单 —— **只有三条**。
 *
 * 三条都必须满足：① **整行**锚定（`^…$`）；② 形态**可枚举**；
 * ③ 在真实语料上**逐条抽样核对过**。
 *
 * ⚠️ 不要往里加「看起来也像噪声」的规则。实测教训：
 * 一条含 `整理`/`免费`/`转自` 的推广行规则在儒林外史命中 6 段、
 * 红楼梦命中 13 段，**抽样全是正文**（「须臾，**整理**停当，何美之捧出盘子…」）。
 * 通用降噪规则会**静默删掉正文**，而删掉之后没有任何信号。
 *
 * 三条各自的实测命中量（真实解析器切段后逐行匹配，2026-10-10）：
 *
 * | 模式 | 儒林外史 | 红楼梦 |
 * | --- | --- | --- |
 * | 字数标记 | 57 行 | 0 |
 * | 分隔线 | 57 行 | 0 |
 * | 本章完标记 | 0 | 120 行 |
 * | **合计** | **114 行 / 1539 字** | **120 行 / 600 字** |
 */
export const STRUCTURAL_NOISE_PATTERNS: readonly NoisePattern[] = [
  ["字数标记", /^本章字数\s*[:：]\s*\d+$/u],
  ["分隔线", /^[-=_*~·—]{4,}$/u],
  ["本章完标记", /^[(（]\s*本章完\s*[)）]$/u]
];

/**
 * 删除结构性噪声行，并返回**删除区间清单**。
 *
 * ## 只删整行，不做任何子串替换
 *
 * 这是本函数唯一的安全边界。子串替换（例如把 `本章字数:7415` 从一行中间抠掉）
 * 会让「删除」变成「改写」，而改写**没有区间清单可言** —— 审计链会断掉，
 * 金标的「回号 + 段号 + 原文引用」也就核对不了了。
 *
 * ## 段落序号会移动（已知且必须记住的副作用）
 *
 * 删行会改变 `splitParagraphs` 的段落编号。实测：
 * 儒林外史第一回的 `本章字数:7415` 在**头部** → 该回叙事段号 **−1**；
 * 红楼梦第一回的 `(本章完)` 在**尾部** → 平移 **0**。
 * 因此接进导入路径时，儒林外史的金标段号需要同步 −1。
 *
 * @param text 文本（**应已过 {@link normalizeEncoding}**；未归一时行尾的 `\r` 靠 `trim()` 兜住）
 * @returns 剥离后的文本 + 删除区间清单
 */
export function stripStructuralNoise(text: string): StripNoiseResult {
  const kept: string[] = [];
  const deletions: DeletedLine[] = [];

  text.split("\n").forEach((line, index) => {
    const trimmed = line.trim();
    const hit = STRUCTURAL_NOISE_PATTERNS.find(([, pattern]) => pattern.test(trimmed));
    if (hit === undefined) {
      kept.push(line);
      return;
    }
    deletions.push({ lineNo: index + 1, label: hit[0], text: trimmed });
  });

  return { text: kept.join("\n"), deletions };
}
